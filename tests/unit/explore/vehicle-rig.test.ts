import { expect, it } from 'vitest';
import * as THREE from 'three';
import { createScope } from '../../../src/shared/lifecycle';
import type { createScene } from '../../../src/chapters/explore/scene';
import { createVehicleRig } from '../../../src/chapters/explore/vehicle-rig';

it('keeps authored door, tailgate, light and explosion transforms', () => {
  const scene = new THREE.Scene();
  const roadSurface = new THREE.Group();
  const scope = createScope();
  const rig = createVehicleRig({ scene, roadSurface } as ReturnType<typeof createScene>, scope);
  const root = new THREE.Group();
  const assembly = new THREE.Group();
  assembly.name = 'EV_SUV';
  root.add(assembly);
  const nodes = ['Door_FL', 'Door_FR', 'Tailgate', 'BatteryPack'].map((name, index) => {
    const material = new THREE.MeshStandardMaterial();
    material.name = 'daylight_led';
    const mesh = new THREE.Mesh(new THREE.BoxGeometry(0.1, 0.1, 0.1), material);
    mesh.name = name;
    mesh.position.x = index * 10;
    mesh.rotation.set(0, 0.1, 0.2);
    mesh.userData.explode_vector_blender_m = [0, 1, 0];
    assembly.add(mesh);
    return mesh;
  });
  rig.prepareModel(root);
  rig.prepareExplosionRigs();
  expect(rig.assemblyRoot).toBe(assembly);
  expect(rig.toggleDoors()).toBe(true);
  expect(rig.toggleTailgate()).toBe(true);
  expect(rig.toggleLights()).toBe(true);
  rig.update(2);
  expect(nodes[0].rotation.y).toBeCloseTo(0.1 - 0.72);
  expect(nodes[1].rotation.y).toBeCloseTo(0.1 + 0.72);
  expect(nodes[2].rotation.z).toBeCloseTo(0.2 - 0.95);
  expect(nodes[0].material.emissiveIntensity).toBe(1.7);
  rig.setExploded(true);
  rig.update(2);
  expect(roadSurface.visible).toBe(false);
  expect(nodes[3].position.y).toBeCloseTo(1.55, 3);
  expect(rig.applyPartFilter('energy')).toBe(1);
  expect(nodes[0].visible).toBe(false);
  expect(nodes[3].visible).toBe(true);
  rig.setExploded(false);
  rig.update(2);
  expect(roadSurface.visible).toBe(true);
  expect(nodes[3].position.y).toBeCloseTo(0, 3);
  expect(rig.toggleLights()).toBe(false);
  expect(nodes[0].material.emissiveIntensity).toBe(0.06);
  scope.dispose();
});
